export function knownSongMeta(title: string): KnownSongMeta | null {
  return KNOWN_SONG_META[normalizeName(title)] ?? null;
}

export function normalizeName(value: string): string {
  return value
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}

